"""
Grad-CAM explainability for the hierarchical multi-scale classifier.

Implements FR6 / the Explainability Layer from the Phase 1 report: generates
a separate Grad-CAM heatmap for EACH hierarchical stage (Stage 1: Normal vs
Abnormal, Stage 2: disease type), matching the report's explicit design goal
of "Grad-CAM at each stage separately" — not just one heatmap for a single
flat prediction.

By default, auto-selects clinically meaningful examples from
outputs/evaluation/test_predictions.csv (generated by evaluate.py):
  - a confident CORRECT Tuberculosis prediction
  - the dominant failure mode: Pneumonia predicted as Normal
  - the second failure mode: COVID-19 predicted as Tuberculosis
You can also pass specific image paths via --paths.

Run from project root (after evaluate.py has been run at least once):
    python scripts/gradcam_explain.py
"""
import sys
import time
import argparse
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "src"))

import torch
import torch.nn as nn
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt

from pytorch_grad_cam import GradCAM
from pytorch_grad_cam.utils.image import show_cam_on_image
from pytorch_grad_cam.utils.model_targets import ClassifierOutputTarget

from preprocessing import load_grayscale, apply_clahe, resize, grayscale_to_rgb, IMAGENET_MEAN, IMAGENET_STD
from model import MultiScaleEfficientNet

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_SEED = 42

STAGE2_LABELS = ["Pneumonia", "Tuberculosis", "COVID-19"]


class StageWrapper(nn.Module):
    """pytorch_grad_cam expects a model whose forward() returns a single
    logits tensor. Our model returns (stage1_logits, stage2_logits), so this
    wrapper exposes one stage at a time as the "model" Grad-CAM sees."""

    def __init__(self, base_model, stage):
        super().__init__()
        assert stage in ("stage1", "stage2")
        self.base_model = base_model
        self.stage = stage

    def forward(self, x):
        stage1_logits, stage2_logits = self.base_model(x)
        return stage1_logits if self.stage == "stage1" else stage2_logits


def preprocess_image(path):
    """Returns (normalized_tensor[1,3,224,224], display_rgb_float[0,1] for overlay)."""
    gray = load_grayscale(path)
    gray = apply_clahe(gray)
    gray = resize(gray)
    rgb = grayscale_to_rgb(gray)

    display_rgb = rgb.astype(np.float32) / 255.0  # for show_cam_on_image, HWC, [0,1]

    img = display_rgb.copy()
    img = (img - IMAGENET_MEAN) / IMAGENET_STD
    img = np.transpose(img, (2, 0, 1))
    tensor = torch.from_numpy(img).float().unsqueeze(0)

    return tensor, display_rgb


def pick_all_examples(predictions_csv):
    """Every row of test_predictions.csv, for the full-test-set Grad-CAM run."""
    if not predictions_csv.exists():
        raise FileNotFoundError(
            f"{predictions_csv} not found. Run scripts/evaluate.py first "
            "(with the updated version that saves image_path)."
        )
    df = pd.read_csv(predictions_csv)
    examples = []
    for idx, row in df.iterrows():
        examples.append({
            "path": row.image_path, "true": row.true_label, "pred": row.pred_label,
            "tag": f"{idx:05d}_{row.true_label}_as_{row.pred_label}",
        })
    return examples


def build_gradcam_engines(model, device):
    """Builds the Stage 1 / Stage 2 GradCAM engines ONCE, reused across every
    image. Rebuilding these per-image (as the original 3-example version did)
    is fine for 3 images but wasteful at full-test-set scale (6,717 images x 2
    stages) — each rebuild re-registers forward/backward hooks."""
    target_layer = [model.backbone[8]]
    stage1_wrapper = StageWrapper(model, "stage1").to(device).eval()
    stage2_wrapper = StageWrapper(model, "stage2").to(device).eval()
    cam1 = GradCAM(model=stage1_wrapper, target_layers=target_layer)
    cam2 = GradCAM(model=stage2_wrapper, target_layers=target_layer)
    return cam1, cam2
    """Pull three clinically meaningful examples from test_predictions.csv:
    a confident correct TB case, the Pneumonia->Normal failure mode, and the
    COVID-19->Tuberculosis failure mode — both identified from the confusion
    matrix as the dataset's dominant error patterns."""
    if not predictions_csv.exists():
        raise FileNotFoundError(
            f"{predictions_csv} not found. Run scripts/evaluate.py first "
            "(with the updated version that saves image_path)."
        )
    df = pd.read_csv(predictions_csv)
    examples = []

    # 1) Confident correct TB prediction
    tb_correct = df[(df.true_label == "Tuberculosis") & (df.pred_label == "Tuberculosis")]
    tb_correct = tb_correct.sort_values("prob_Tuberculosis", ascending=False)
    if len(tb_correct):
        row = tb_correct.iloc[0]
        examples.append({
            "path": row.image_path, "true": row.true_label, "pred": row.pred_label,
            "tag": "correct_TB_high_confidence",
        })

    # 2) Dominant failure mode: Pneumonia -> Normal
    pneu_as_normal = df[(df.true_label == "Pneumonia") & (df.pred_label == "Normal")]
    if len(pneu_as_normal):
        row = pneu_as_normal.iloc[0]
        examples.append({
            "path": row.image_path, "true": row.true_label, "pred": row.pred_label,
            "tag": "failure_pneumonia_as_normal",
        })

    # 3) Second failure mode: COVID-19 -> Tuberculosis
    covid_as_tb = df[(df.true_label == "COVID-19") & (df.pred_label == "Tuberculosis")]
    if len(covid_as_tb):
        row = covid_as_tb.iloc[0]
        examples.append({
            "path": row.image_path, "true": row.true_label, "pred": row.pred_label,
            "tag": "failure_covid_as_tb",
        })

    if not examples:
        raise RuntimeError("Could not find any of the target example patterns in test_predictions.csv")

    return examples


def classify_attention_zone(cam, corner_frac=0.18, margin_frac=0.07, midline_half_width=0.09):
    """Classifies WHERE a Grad-CAM heatmap's attention is concentrated into a
    coarse zone: 'corner_marker', 'outer_margin', 'midline_strip', or
    'lung_field'. Uses the heatmap's PEAK (single hottest pixel), not its
    weighted centroid.

    NOTE: an earlier centroid-based version of this function was tried and
    discarded — Grad-CAM heatmaps are diffuse after upsampling, so even a
    real, visually obvious corner hot-spot gets averaged away by the rest of
    the (centrally-weighted) heatmap when using a centroid, making corner/
    margin artifacts undetectable. The peak location is sensitive to a
    genuine hot spot even when the rest of the map is diffuse elsewhere.

    IMPORTANT CAVEAT: this is a geometric heuristic based on typical CXR
    layout (patient roughly centered, position markers/brackets usually in
    the top corners) — NOT a real lung-segmentation mask. It approximates
    "non-anatomical vs lung-field" rather than proving it. Appropriate for
    quantifying a limitation across the test set; not a clinical claim.
    """
    h, w = cam.shape
    if cam.max() <= 0:
        return "undefined"

    peak_y, peak_x = np.unravel_index(np.argmax(cam), cam.shape)
    fy, fx = peak_y / h, peak_x / w  # normalized to [0, 1]

    in_top_corner = (fy < corner_frac) and (fx < corner_frac or fx > 1 - corner_frac)
    in_outer_margin = (fx < margin_frac) or (fx > 1 - margin_frac) or (fy < margin_frac) or (fy > 1 - margin_frac)
    in_midline = abs(fx - 0.5) < midline_half_width

    if in_top_corner:
        return "corner_marker"
    if in_outer_margin:
        return "outer_margin"
    if in_midline:
        return "midline_strip"
    return "lung_field"


def generate_gradcam_figure(model, example, device, cam1, cam2, out_dir, save_figure=True):
    path = example["path"]
    tensor, display_rgb = preprocess_image(path)
    tensor = tensor.to(device)

    with torch.no_grad():
        s1_logits, s2_logits = model(tensor)
    stage1_pred_idx = s1_logits.argmax(dim=1).item()
    stage2_pred_idx = s2_logits.argmax(dim=1).item()

    grayscale_cam1 = cam1(input_tensor=tensor, targets=[ClassifierOutputTarget(stage1_pred_idx)])[0]
    overlay1 = show_cam_on_image(display_rgb, grayscale_cam1, use_rgb=True)
    stage1_zone = classify_attention_zone(grayscale_cam1)

    stage1_label = "Abnormal" if stage1_pred_idx == 1 else "Normal"

    # Stage 2 is only trained on Abnormal images (stage2 label is -1/ignored
    # for every Normal row in dataset.py, masked out via
    # CrossEntropyLoss(ignore_index=-1)). When Stage 1 predicts Normal,
    # combine_predictions() never looks at Stage 2's output — the final
    # label is Normal regardless. Forcing a Stage 2 Grad-CAM on an image its
    # head was never trained to classify produces a meaningless heatmap that
    # LOOKS like a real disagreement but isn't one, so we skip generating it
    # and label the panel accordingly instead.
    stage2_is_meaningful = (stage1_pred_idx == 1)

    if stage2_is_meaningful:
        grayscale_cam2 = cam2(input_tensor=tensor, targets=[ClassifierOutputTarget(stage2_pred_idx)])[0]
        overlay2 = show_cam_on_image(display_rgb, grayscale_cam2, use_rgb=True)
        stage2_label = STAGE2_LABELS[stage2_pred_idx]
        stage2_title = f"Stage 2 Grad-CAM\nPredicted: {stage2_label}"
        stage2_zone = classify_attention_zone(grayscale_cam2)
    else:
        overlay2 = display_rgb  # plain input, no heatmap — nothing meaningful to show
        stage2_label = "N/A"
        stage2_title = "Stage 2 Grad-CAM\nN/A (Stage 1 = Normal, Stage 2 not used)"
        stage2_zone = "N/A"

    out_path = None
    if save_figure:
        fig, axes = plt.subplots(1, 3, figsize=(15, 5))
        axes[0].imshow(display_rgb)
        axes[0].set_title(f"Input\nTrue: {example['true']} | Predicted: {example['pred']}")
        axes[0].axis("off")

        axes[1].imshow(overlay1)
        axes[1].set_title(f"Stage 1 Grad-CAM\nPredicted: {stage1_label}")
        axes[1].axis("off")

        axes[2].imshow(overlay2)
        axes[2].set_title(stage2_title)
        axes[2].axis("off")

        plt.tight_layout()
        out_path = out_dir / f"gradcam_{example['tag']}.png"
        plt.savefig(out_path, dpi=150)
        plt.close()

    return out_path, stage1_label, stage2_label, stage1_zone, stage2_zone


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--paths", nargs="*", default=None,
                         help="Optional specific image paths instead of auto-selected examples")
    parser.add_argument("--all-test", action="store_true",
                         help="Generate Grad-CAM for EVERY image in test_predictions.csv "
                              "(both stages), instead of just 3 auto-selected examples. "
                              "~30-60 min on a GPU for the full 6,717-image test set. "
                              "Ignored if --paths is given.")
    parser.add_argument("--seed", type=int, default=DEFAULT_SEED,
                         help="Which seeded checkpoint/predictions to use (must match "
                              "the --seed used for train.py / evaluate.py).")
    args = parser.parse_args()

    suffix = "" if args.seed == DEFAULT_SEED else f"_seed{args.seed}"
    checkpoint_path = ROOT / "outputs" / f"checkpoints{suffix}" / "best_model.pt"
    predictions_csv = ROOT / "outputs" / f"evaluation{suffix}" / "test_predictions.csv"
    # Full-test-set runs go to their own folder — keeps the original 3-example
    # "gradcam" folder (used in your report figures) untouched.
    out_dir_name = f"gradcam_full{suffix}" if args.all_test and not args.paths else f"gradcam{suffix}"
    out_dir = ROOT / "outputs" / out_dir_name
    out_dir.mkdir(parents=True, exist_ok=True)

    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    print(f"Using device: {device}")
    print(f"Seed={args.seed} | checkpoint: {checkpoint_path} | output: {out_dir}")

    model = MultiScaleEfficientNet(pretrained=False, freeze_backbone=False).to(device)
    model.load_state_dict(torch.load(checkpoint_path, map_location=device))
    model.eval()

    if args.paths:
        examples = [{"path": p, "true": "?", "pred": "?", "tag": f"custom_{i}"}
                    for i, p in enumerate(args.paths)]
    elif args.all_test:
        examples = pick_all_examples(predictions_csv)
        print(f"Running Grad-CAM on ALL {len(examples)} test images "
              f"(both stages) — this will take a while.")
    else:
        examples = pick_auto_examples(predictions_csv)
        print(f"Auto-selected {len(examples)} examples:")
        for e in examples:
            print(f"  [{e['tag']}] true={e['true']} pred={e['pred']} path={e['path']}")

    # Build the GradCAM engines once and reuse across all images — important
    # for the --all-test case, where rebuilding hooks 6,717 times would be wasteful.
    cam1, cam2 = build_gradcam_engines(model, device)

    log_path = out_dir / "gradcam_log.csv"
    log_rows = []
    t_start = time.time()
    SAVE_EVERY = 200  # write the log periodically so a crash/interrupt doesn't lose everything

    for i, example in enumerate(examples):
        out_path, stage1_label, stage2_label, stage1_zone, stage2_zone = generate_gradcam_figure(
            model, example, device, cam1, cam2, out_dir
        )
        log_rows.append({
            "image_path": example["path"],
            "true_label": example["true"],
            "pred_label": example["pred"],
            "stage1_pred": stage1_label,
            "stage2_pred": stage2_label,
            "stage1_attention_zone": stage1_zone,
            "stage2_attention_zone": stage2_zone,
            "output_file": out_path.name if out_path else None,
        })

        if args.all_test:
            done = (i + 1) == len(examples)
            if (i + 1) % SAVE_EVERY == 0 or done:
                pd.DataFrame(log_rows).to_csv(log_path, index=False)
                elapsed = time.time() - t_start
                rate = (i + 1) / elapsed
                eta_min = (len(examples) - (i + 1)) / rate / 60 if rate > 0 else 0
                print(f"[{i+1}/{len(examples)}] {elapsed/60:.1f} min elapsed, "
                      f"ETA {eta_min:.1f} min | log saved -> {log_path}")
        else:
            print(f"Saved: {out_path}")

    total_min = (time.time() - t_start) / 60
    if args.all_test and not args.paths:
        print(f"\nDone in {total_min:.1f} min. Log ({len(log_rows)} rows): {log_path}")
    print(f"All Grad-CAM figures saved to: {out_dir}")


if __name__ == "__main__":
    main()
